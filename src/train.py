"""
Train an audio-only, video-only, or fusion emotion classifier.

Usage:
    python src/train.py --data_dir data/processed --modality audio
    python src/train.py --data_dir data/processed --modality video
    python src/train.py --data_dir data/processed --modality fusion --fusion late
    python src/train.py --data_dir data/processed --modality fusion --fusion attention
"""
import argparse
import os
import random
import torch
import torch.nn as nn
import numpy as np
from torch.utils.data import DataLoader
from sklearn.metrics import accuracy_score, f1_score, roc_auc_score
from tqdm import tqdm

from dataset import AVEmotionDataset, EMOTION_TO_IDX
from models import AVEmotionModel
from face_geometry import LANDMARK_GEOMETRY_DIM, LANDMARK_FEATURE_DIM


def run_epoch(model, loader, device, optimizer=None, class_weights=None, use_landmarks=False,
              label_smoothing=0.0):
    train = optimizer is not None
    model.train() if train else model.eval()
    criterion = nn.CrossEntropyLoss(weight=class_weights, label_smoothing=label_smoothing)

    total_loss, all_preds, all_labels, all_probs = 0.0, [], [], []
    with torch.set_grad_enabled(train):
        for batch in loader:
            mel = batch["mel"].to(device)
            frames = batch["frames"].to(device)
            landmarks = batch.get("landmarks")
            if landmarks is not None:
                landmarks = landmarks.to(device)
            if train and not use_landmarks and random.random() < 0.5:
                frames = frames.flip(-1)
            labels = batch["label"].to(device)

            logits = model(mel=mel, frames=frames, landmarks=landmarks)
            all_probs.extend(torch.softmax(logits.detach(), dim=-1).cpu().numpy())
            loss = criterion(logits, labels)

            if train:
                optimizer.zero_grad()
                loss.backward()
                optimizer.step()

            total_loss += loss.item() * labels.size(0)
            all_preds.extend(logits.argmax(dim=-1).cpu().tolist())
            all_labels.extend(labels.cpu().tolist())

    avg_loss = total_loss / len(loader.dataset)
    acc = accuracy_score(all_labels, all_preds)
    f1 = f1_score(all_labels, all_preds, average="macro")
    auc = roc_auc_score(all_labels, np.asarray(all_probs), multi_class="ovr",
                        average="macro", labels=np.arange(len(EMOTION_TO_IDX)))
    return avg_loss, acc, f1, auc


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data_dir", default="data/processed")
    ap.add_argument("--modality", choices=["audio", "video", "fusion"], required=True)
    ap.add_argument("--fusion", choices=["late", "attention"], default="late")
    ap.add_argument("--epochs", type=int, default=20)
    ap.add_argument("--batch_size", type=int, default=16)
    ap.add_argument("--lr", type=float, default=1e-3)
    ap.add_argument("--checkpoint_dir", default="checkpoints")
    ap.add_argument("--patience", type=int, default=5)
    ap.add_argument("--weight_decay", type=float, default=1e-4)
    ap.add_argument("--backbone_lr", type=float, default=1e-5)
    ap.add_argument("--freeze_backbone", action="store_true",
                    help="Train the projection and classifier while freezing all ResNet blocks.")
    ap.add_argument("--class_weights", action="store_true",
                    help="Use inverse-frequency weights to optimize macro-F1 on the imbalanced labels.")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--num_workers", type=int, default=0)
    ap.add_argument("--use_landmarks", action="store_true",
                    help="Fuse tracked face-mesh geometry with audio and video features.")
    ap.add_argument("--landmark_dir", default="data/landmarks")
    ap.add_argument("--face_frame_dir", default=None,
                    help="Train from face-only crops generated by scripts/extract_face_crops.py.")
    ap.add_argument("--landmark_feature_mode", choices=["geometry", "blendshapes"],
                    default="geometry")
    ap.add_argument("--init_checkpoint", default=None,
                    help="Optionally initialize from an existing compatible checkpoint.")
    ap.add_argument("--label_smoothing", type=float, default=0.0)
    ap.add_argument("--selection_metric", choices=["macro_f1", "accuracy", "auroc"],
                    default="macro_f1")
    args = ap.parse_args()
    if args.use_landmarks and args.modality != "fusion":
        ap.error("--use_landmarks requires --modality fusion")

    random.seed(args.seed)
    np.random.seed(args.seed)
    torch.manual_seed(args.seed)
    torch.backends.cudnn.benchmark = False
    torch.backends.cudnn.deterministic = True
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(args.seed)

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    os.makedirs(args.checkpoint_dir, exist_ok=True)

    train_ds = AVEmotionDataset(args.data_dir, "train", include_landmarks=args.use_landmarks,
                                landmark_dir=args.landmark_dir,
                                landmark_feature_mode=args.landmark_feature_mode,
                                face_frame_dir=args.face_frame_dir)
    val_ds = AVEmotionDataset(args.data_dir, "val", include_landmarks=args.use_landmarks,
                              landmark_dir=args.landmark_dir,
                              landmark_feature_mode=args.landmark_feature_mode,
                              face_frame_dir=args.face_frame_dir)
    train_loader = DataLoader(train_ds, batch_size=args.batch_size, shuffle=True,
                              num_workers=args.num_workers)
    val_loader = DataLoader(val_ds, batch_size=args.batch_size, shuffle=False,
                            num_workers=args.num_workers)

    n_classes = len(EMOTION_TO_IDX)
    model = AVEmotionModel(modality=args.modality, fusion_type=args.fusion,
                            n_classes=n_classes,
                            use_landmarks=args.use_landmarks,
                            landmark_feature_dim=(LANDMARK_GEOMETRY_DIM
                                                  if args.landmark_feature_mode == "geometry"
                                                  else LANDMARK_FEATURE_DIM),
                            fine_tune_backbone=not args.freeze_backbone).to(device)
    if args.init_checkpoint:
        init_state = torch.load(args.init_checkpoint, map_location=device, weights_only=True)
        model_state = model.state_dict()
        compatible = {name: value for name, value in init_state.items()
                      if name in model_state and value.shape == model_state[name].shape}
        missing, unexpected = model.load_state_dict(compatible, strict=False)
        print(f"Initialized {len(compatible)} tensors from {args.init_checkpoint}; "
              f"new parameters: {missing}; "
              f"unused parameters: {unexpected}")
    backbone_params = []
    if hasattr(model, "video_encoder"):
        backbone_params = [p for p in model.video_encoder.backbone.parameters() if p.requires_grad]
    backbone_ids = {id(p) for p in backbone_params}
    head_params = [p for p in model.parameters() if p.requires_grad and id(p) not in backbone_ids]
    param_groups = [{"params": head_params, "lr": args.lr}]
    if backbone_params:
        param_groups.append({"params": backbone_params, "lr": args.backbone_lr})
    optimizer = torch.optim.AdamW(param_groups, weight_decay=args.weight_decay)
    class_weights = None
    if args.class_weights:
        counts = torch.bincount(
            torch.tensor(train_ds.manifest["label"].to_numpy(), dtype=torch.long),
            minlength=n_classes,
        ).float()
        class_weights = (counts.sum() / (n_classes * counts)).to(device)

    tag = args.modality if args.modality != "fusion" else f"fusion_{args.fusion}"
    if args.use_landmarks:
        tag += "_landmarks"
        if args.landmark_feature_mode == "blendshapes":
            tag += "_blendshapes"
    if args.face_frame_dir:
        tag += "_face"
    best_score, patience_ctr = -1.0, 0

    for epoch in range(1, args.epochs + 1):
        train_loss, train_acc, train_f1, train_auc = run_epoch(
            model, train_loader, device, optimizer, class_weights, args.use_landmarks,
            args.label_smoothing
        )
        val_loss, val_acc, val_f1, val_auc = run_epoch(
            model, val_loader, device, optimizer=None, use_landmarks=args.use_landmarks,
            label_smoothing=args.label_smoothing
        )

        print(f"[{tag}] epoch {epoch:02d} | train loss {train_loss:.3f} acc {train_acc:.3f} "
              f"| val loss {val_loss:.3f} acc {val_acc:.3f} f1 {val_f1:.3f} auc {val_auc:.3f}")

        score = {"macro_f1": val_f1, "accuracy": val_acc, "auroc": val_auc}[args.selection_metric]
        if score > best_score:
            best_score = score
            patience_ctr = 0
            torch.save(model.state_dict(), os.path.join(args.checkpoint_dir, f"{tag}.pt"))
        else:
            patience_ctr += 1
            if patience_ctr >= args.patience:
                print(f"Early stopping at epoch {epoch} (best val {args.selection_metric} {best_score:.3f})")
                break

    print(f"Best val {args.selection_metric} for {tag}: {best_score:.3f} -> saved to "
          f"{args.checkpoint_dir}/{tag}.pt")


if __name__ == "__main__":
    main()
