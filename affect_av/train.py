"""
Train an audio-only, video-only, or fusion emotion classifier.

Usage:
    affect-train --data_dir data/processed --modality audio
    affect-train --data_dir data/processed --modality video
    affect-train --data_dir data/processed --modality fusion --fusion late
    affect-train --data_dir data/processed --modality fusion --fusion attention
"""
import argparse
import os
import random
import torch
import torch.nn as nn
import numpy as np
from torch.utils.data import DataLoader
from sklearn.metrics import accuracy_score, f1_score, roc_auc_score

from .augment import augment_config_from_args, augmentation_enabled
from .checkpoints import config_from_training, save_checkpoint
from .dataset import AVEmotionDataset, EMOTION_TO_IDX, MEL_NORM_MODES
from .models import AVEmotionModel
from .face_geometry import LANDMARK_GEOMETRY_DIM, LANDMARK_FEATURE_DIM


def run_epoch(model, loader, device, optimizer=None, class_weights=None,
              label_smoothing=0.0, aux_loss_weight=0.0):
    """Run one epoch; auxiliary head losses are added scaled by ``aux_loss_weight``."""
    train = optimizer is not None
    model.train() if train else model.eval()
    criterion = nn.CrossEntropyLoss(weight=class_weights, label_smoothing=label_smoothing)

    total_loss, all_preds, all_labels, all_probs = 0.0, [], [], []
    with torch.set_grad_enabled(train):
        for batch in loader:
            mel = batch["mel"].to(device)
            frames = batch["frames"].to(device)
            landmarks = batch.get("landmarks")
            if landmarks is not None:
                landmarks = landmarks.to(device)
            waveform = batch.get("waveform")
            if waveform is not None:
                waveform = waveform.to(device)
            labels = batch["label"].to(device)

            outputs = model(mel=mel, frames=frames, landmarks=landmarks,
                            waveform=waveform, return_aux=aux_loss_weight > 0)
            if aux_loss_weight > 0:
                logits = outputs["logits"]
            else:
                logits = outputs
            all_probs.extend(torch.softmax(logits.detach(), dim=-1).cpu().numpy())
            loss = criterion(logits, labels)
            if aux_loss_weight > 0:
                aux_loss = (criterion(outputs["aux_audio"], labels)
                            + criterion(outputs["aux_video"], labels))
                loss = loss + aux_loss_weight * aux_loss

            if train:
                optimizer.zero_grad()
                loss.backward()
                optimizer.step()

            total_loss += loss.item() * labels.size(0)
            all_preds.extend(logits.argmax(dim=-1).cpu().tolist())
            all_labels.extend(labels.cpu().tolist())

    avg_loss = total_loss / len(loader.dataset)
    acc = accuracy_score(all_labels, all_preds)
    f1 = f1_score(all_labels, all_preds, average="macro")
    auc = roc_auc_score(all_labels, np.asarray(all_probs), multi_class="ovr",
                        average="macro", labels=np.arange(len(EMOTION_TO_IDX)))
    return avg_loss, acc, f1, auc


def build_parser() -> argparse.ArgumentParser:
    """Training CLI; cross-validation reuses these flags."""
    ap = argparse.ArgumentParser()
    ap.add_argument("--data_dir", default="data/processed")
    ap.add_argument("--manifest", default=None,
                    help="Optional manifest CSV (default: <data_dir>/manifest.csv).")
    ap.add_argument("--modality", choices=["audio", "video", "fusion"], required=True)
    ap.add_argument("--fusion", choices=["late", "attention"], default="late")
    ap.add_argument("--epochs", type=int, default=20)
    ap.add_argument("--batch_size", type=int, default=16)
    ap.add_argument("--lr", type=float, default=1e-3)
    ap.add_argument("--checkpoint_dir", default="checkpoints")
    ap.add_argument("--patience", type=int, default=5)
    ap.add_argument("--weight_decay", type=float, default=1e-4)
    ap.add_argument("--backbone_lr", type=float, default=1e-5)
    ap.add_argument("--freeze_backbone", action="store_true",
                    help="Train the projection and classifier while freezing all ResNet blocks.")
    ap.add_argument("--class_weights", action="store_true",
                    help="Use inverse-frequency weights to optimize macro-F1 on the imbalanced labels.")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--num_workers", type=int, default=0)
    ap.add_argument("--use_landmarks", action="store_true",
                    help="Fuse tracked face-mesh geometry with audio and video features.")
    ap.add_argument("--landmark_dir", default="data/landmarks")
    ap.add_argument("--face_frame_dir", default=None,
                    help="Train from face-only crops generated by scripts/extract_face_crops.py.")
    ap.add_argument("--landmark_feature_mode", choices=["geometry", "blendshapes"],
                    default="geometry")
    ap.add_argument("--audio_encoder", choices=["cnn", "wavlm"], default="cnn",
                    help="Log-mel CNN (default) or a frozen-lower WavLM waveform encoder.")
    ap.add_argument("--wavlm_model", default="microsoft/wavlm-base")
    ap.add_argument("--wavlm_freeze_layers", type=int, default=8,
                    help="Number of lowest WavLM transformer layers kept frozen.")
    ap.add_argument("--wavlm_lr", type=float, default=1e-4,
                    help="Learning rate for unfrozen WavLM transformer layers.")
    ap.add_argument("--mel_norm", choices=MEL_NORM_MODES, default="global")
    ap.add_argument("--mel_stats", default=None,
                    help="Mel stats path (default: <data_dir>/stats.json).")
    ap.add_argument("--init_checkpoint", default=None,
                    help="Optionally initialize from an existing compatible checkpoint.")
    ap.add_argument("--label_smoothing", type=float, default=0.0)
    ap.add_argument("--selection_metric", choices=["macro_f1", "accuracy", "auroc"],
                    default="macro_f1")
    ap.add_argument("--aug_resized_crop_scale", type=float, default=0.0,
                    help="Random resized crop area fraction lower bound (0 disables).")
    ap.add_argument("--aug_flip_p", type=float, default=0.0,
                    help="Per-clip horizontal flip probability (0 disables).")
    ap.add_argument("--aug_color_jitter", type=float, default=0.0,
                    help="Brightness/contrast/saturation jitter magnitude in [0, 1].")
    ap.add_argument("--aug_rotation_deg", type=float, default=0.0,
                    help="Maximum absolute rotation in degrees (0 disables).")
    ap.add_argument("--aug_gain_db", type=float, default=0.0,
                    help="Maximum absolute random audio gain in dB, applied before normalization.")
    ap.add_argument("--aug_noise_std", type=float, default=0.0,
                    help="Gaussian noise std added to the normalized mel spectrogram.")
    ap.add_argument("--specaugment", action="store_true",
                    help="Apply SpecAugment time/frequency masks after normalization.")
    ap.add_argument("--specaug_time_masks", type=int, default=2)
    ap.add_argument("--specaug_time_width", type=int, default=12)
    ap.add_argument("--specaug_freq_masks", type=int, default=2)
    ap.add_argument("--specaug_freq_width", type=int, default=8)
    ap.add_argument("--modality_dropout", type=float, default=0.0,
                    help="Per-modality probability of replacing an embedding with a learned "
                         "missing token during fusion training (never both modalities).")
    ap.add_argument("--aux_heads", action="store_true",
                    help="Add audio-only and video-only auxiliary heads to a fusion model.")
    ap.add_argument("--aux_loss_weight", type=float, default=0.3,
                    help="Weight applied to each auxiliary head loss.")
    return ap


def validate_args(args) -> None:
    """Raise ``ValueError`` for invalid flag combinations."""
    if args.use_landmarks and args.modality != "fusion":
        raise ValueError("--use_landmarks requires --modality fusion")
    if (args.modality_dropout > 0 or args.aux_heads) and args.modality != "fusion":
        raise ValueError("--modality_dropout and --aux_heads require --modality fusion")
    if not 0.0 <= args.modality_dropout <= 1.0:
        raise ValueError("--modality_dropout must be in [0, 1]")
    if args.aux_loss_weight < 0:
        raise ValueError("--aux_loss_weight must be >= 0")
    if args.audio_encoder == "wavlm" and args.modality == "video":
        raise ValueError("--audio_encoder wavlm requires an audio or fusion model")
    if args.wavlm_freeze_layers < 0:
        raise ValueError("--wavlm_freeze_layers must be >= 0")
    if args.wavlm_lr <= 0:
        raise ValueError("--wavlm_lr must be > 0")
    if args.epochs <= 0:
        raise ValueError("--epochs must be > 0")
    if args.batch_size <= 0:
        raise ValueError("--batch_size must be > 0")
    augment_config_from_args(args)


def _seed_everything(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.backends.cudnn.benchmark = False
    torch.backends.cudnn.deterministic = True
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def train(args) -> dict:
    """Run one training job described by ``args`` and return its summary.

    The CLI and cross-validation both call this function. It saves the best
    checkpoint (plus sidecar) under ``args.checkpoint_dir`` and returns the tag,
    checkpoint path, best score/epoch, epochs run, and per-epoch history.
    """
    validate_args(args)
    augment_config = augment_config_from_args(args)
    _seed_everything(args.seed)

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    os.makedirs(args.checkpoint_dir, exist_ok=True)
    manifest_path = getattr(args, "manifest", None)

    include_waveform = args.audio_encoder == "wavlm"
    train_ds = AVEmotionDataset(args.data_dir, "train", include_landmarks=args.use_landmarks,
                                landmark_dir=args.landmark_dir,
                                landmark_feature_mode=args.landmark_feature_mode,
                                face_frame_dir=args.face_frame_dir,
                                mel_norm=args.mel_norm, mel_stats_path=args.mel_stats,
                                augment=augment_config, include_waveform=include_waveform,
                                manifest_path=manifest_path)
    val_ds = AVEmotionDataset(args.data_dir, "val", include_landmarks=args.use_landmarks,
                              landmark_dir=args.landmark_dir,
                              landmark_feature_mode=args.landmark_feature_mode,
                              face_frame_dir=args.face_frame_dir,
                              mel_norm=args.mel_norm, mel_stats_path=args.mel_stats,
                              include_waveform=include_waveform,
                              manifest_path=manifest_path)
    if len(train_ds) == 0:
        raise ValueError(f"No training clips for manifest {manifest_path or args.data_dir}.")
    if len(val_ds) == 0:
        raise ValueError(f"No validation clips for manifest {manifest_path or args.data_dir}.")
    train_loader = DataLoader(train_ds, batch_size=args.batch_size, shuffle=True,
                              num_workers=args.num_workers)
    val_loader = DataLoader(val_ds, batch_size=args.batch_size, shuffle=False,
                            num_workers=args.num_workers)

    n_classes = len(EMOTION_TO_IDX)
    model = AVEmotionModel(modality=args.modality, fusion_type=args.fusion,
                            n_classes=n_classes,
                            use_landmarks=args.use_landmarks,
                            landmark_feature_dim=(LANDMARK_GEOMETRY_DIM
                                                  if args.landmark_feature_mode == "geometry"
                                                  else LANDMARK_FEATURE_DIM),
                            fine_tune_backbone=not args.freeze_backbone,
                            modality_dropout=args.modality_dropout,
                            aux_heads=args.aux_heads,
                            audio_encoder=args.audio_encoder,
                            wavlm_model=args.wavlm_model,
                            wavlm_freeze_layers=args.wavlm_freeze_layers).to(device)
    if augmentation_enabled(augment_config):
        print(f"Augmentation enabled: {augment_config}")
    if args.init_checkpoint:
        init_state = torch.load(args.init_checkpoint, map_location=device, weights_only=True)
        model_state = model.state_dict()
        compatible = {name: value for name, value in init_state.items()
                      if name in model_state and value.shape == model_state[name].shape}
        missing, unexpected = model.load_state_dict(compatible, strict=False)
        print(f"Initialized {len(compatible)} tensors from {args.init_checkpoint}; "
              f"new parameters: {missing}; "
              f"unused parameters: {unexpected}")
    backbone_params = []
    if hasattr(model, "video_encoder"):
        backbone_params = [p for p in model.video_encoder.backbone.parameters() if p.requires_grad]
    wavlm_params = []
    if args.audio_encoder == "wavlm":
        wavlm_params = [p for name, p in model.audio_encoder.named_parameters()
                        if p.requires_grad and name.startswith("backbone.")]
    specialized_ids = {id(p) for p in backbone_params} | {id(p) for p in wavlm_params}
    head_params = [p for p in model.parameters()
                   if p.requires_grad and id(p) not in specialized_ids]
    param_groups = [{"params": head_params, "lr": args.lr}]
    if backbone_params:
        param_groups.append({"params": backbone_params, "lr": args.backbone_lr})
    if wavlm_params:
        param_groups.append({"params": wavlm_params, "lr": args.wavlm_lr})
    optimizer = torch.optim.AdamW(param_groups, weight_decay=args.weight_decay)
    class_weights = None
    if args.class_weights:
        counts = torch.bincount(
            torch.tensor(train_ds.manifest["label"].to_numpy(), dtype=torch.long),
            minlength=n_classes,
        ).float()
        class_weights = (counts.sum() / (n_classes * counts)).to(device)

    tag = args.modality if args.modality != "fusion" else f"fusion_{args.fusion}"
    if args.use_landmarks:
        tag += "_landmarks"
        if args.landmark_feature_mode == "blendshapes":
            tag += "_blendshapes"
    if args.face_frame_dir:
        tag += "_face"
    if args.audio_encoder == "wavlm":
        tag += "_wavlm"
    if args.modality_dropout > 0:
        tag += "_mdrop"
    if args.aux_heads:
        tag += "_aux"
    checkpoint_config = config_from_training(args, tag, model)
    checkpoint_path = os.path.join(args.checkpoint_dir, f"{tag}.pt")
    best_score, best_epoch, patience_ctr = -1.0, None, 0
    history = []
    epochs_run = 0

    for epoch in range(1, args.epochs + 1):
        epochs_run = epoch
        train_loss, train_acc, train_f1, train_auc = run_epoch(
            model, train_loader, device, optimizer, class_weights,
            label_smoothing=args.label_smoothing,
            aux_loss_weight=args.aux_loss_weight if args.aux_heads else 0.0,
        )
        val_loss, val_acc, val_f1, val_auc = run_epoch(
            model, val_loader, device, optimizer=None,
            label_smoothing=args.label_smoothing,
        )
        history.append({
            "epoch": epoch,
            "train_loss": float(train_loss), "train_accuracy": float(train_acc),
            "train_macro_f1": float(train_f1), "train_macro_ovr_auc": float(train_auc),
            "val_loss": float(val_loss), "val_accuracy": float(val_acc),
            "val_macro_f1": float(val_f1), "val_macro_ovr_auc": float(val_auc),
        })

        print(f"[{tag}] epoch {epoch:02d} | train loss {train_loss:.3f} acc {train_acc:.3f} "
              f"| val loss {val_loss:.3f} acc {val_acc:.3f} f1 {val_f1:.3f} auc {val_auc:.3f}")

        score = {"macro_f1": val_f1, "accuracy": val_acc, "auroc": val_auc}[args.selection_metric]
        if score > best_score:
            best_score, best_epoch, patience_ctr = score, epoch, 0
            save_checkpoint(model, checkpoint_path, checkpoint_config)
        else:
            patience_ctr += 1
            if patience_ctr >= args.patience:
                print(f"Early stopping at epoch {epoch} "
                      f"(best val {args.selection_metric} {best_score:.3f})")
                break

    print(f"Best val {args.selection_metric} for {tag}: {best_score:.3f} -> saved to "
          f"{checkpoint_path}")
    return {
        "tag": tag,
        "checkpoint": checkpoint_path,
        "best_score": float(best_score),
        "best_epoch": best_epoch,
        "epochs_run": epochs_run,
        "selection_metric": args.selection_metric,
        "history": history,
    }


def main():
    ap = build_parser()
    args = ap.parse_args()
    try:
        validate_args(args)
    except ValueError as exc:
        ap.error(str(exc))
    train(args)


if __name__ == "__main__":
    main()
